def nwk_name(s):
    return re.sub(r"[\s:;,()\[\]']+", "_", s)


def neighbor_joining(D, names):
    D = np.array(D, dtype=float)
    nodes = [nwk_name(x) for x in names]
    n = len(nodes)
    while n > 2:
        r = D.sum(axis=1)
        Q = (n - 2) * D - r[:, None] - r[None, :]
        np.fill_diagonal(Q, np.inf)
        i, j = np.unravel_index(np.argmin(Q), Q.shape)
        dij = D[i, j]
        li = 0.5 * dij + (r[i] - r[j]) / (2 * (n - 2))
        lj = dij - li
        new = f"({nodes[i]}:{max(li, 0):.5f},{nodes[j]}:{max(lj, 0):.5f})"
        dnew = 0.5 * (D[i] + D[j] - dij)
        keep = [k for k in range(n) if k not in (i, j)]
        Dn = np.zeros((len(keep) + 1, len(keep) + 1))
        Dn[:-1, :-1] = D[np.ix_(keep, keep)]
        Dn[-1, :-1] = dnew[keep]
        Dn[:-1, -1] = dnew[keep]
        D, nodes, n = Dn, [nodes[k] for k in keep] + [new], n - 1
    d = D[0, 1]
    return f"({nodes[0]}:{d / 2:.5f},{nodes[1]}:{d / 2:.5f});"


def upgma_newick(Z, names):
    root = to_tree(Z)

    def rec(node, parent_height):
        bl = max(parent_height - node.dist / 2 if not node.is_leaf() else parent_height, 0)
        if node.is_leaf():
            return f"{nwk_name(names[node.id])}:{bl:.5f}"
        return f"({rec(node.left, node.dist / 2)},{rec(node.right, node.dist / 2)}):{bl:.5f}"

    return f"({rec(root.left, root.dist / 2)},{rec(root.right, root.dist / 2)});"


def silhouette(D, labels):
    labels = np.asarray(labels)
    s = np.zeros(len(labels))
    for i in range(len(labels)):
        same = labels == labels[i]
        if same.sum() < 2:
            continue
        a = D[i, same & (np.arange(len(labels)) != i)].mean()
        b = min(D[i, labels == c].mean() for c in set(labels) if c != labels[i])
        s[i] = (b - a) / max(a, b) if max(a, b) > 0 else 0
    return s.mean()


def choose_clusters(Z, D, k_fixed=None):
    n = D.shape[0]
    if k_fixed:
        return fcluster(Z, k_fixed, "maxclust"), None
    best, scores = (None, -2), {}
    for k in range(2, min(10, n - 1) + 1):
        lab = fcluster(Z, k, "maxclust")
        if len(set(lab)) < 2:
            continue
        scores[k] = silhouette(D, lab)
        if scores[k] > best[1]:
            best = (lab, scores[k])
    return best[0], scores


def pcoa(D):
    n = D.shape[0]
    J = np.eye(n) - np.ones((n, n)) / n
    B = -0.5 * J @ (D ** 2) @ J
    w, v = np.linalg.eigh(B)
    idx = np.argsort(w)[::-1]
    w, v = w[idx], v[:, idx]
    coords = v[:, :2] * np.sqrt(np.maximum(w[:2], 0))
    return coords, np.maximum(w, 0)[:2] / np.maximum(w, 0).sum() * 100


