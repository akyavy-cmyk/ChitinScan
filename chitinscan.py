def spread_labels(ax, fig, xs, ys, texts, colors, fontsize=9, iters=600, seed=0):
    """Place text labels so they do not overlap each other or the points (simple repulsion
    algorithm, no extra packages). Labels far from their point get a thin leader line."""
    rng = np.random.default_rng(seed)
    fig.canvas.draw()
    x0, x1 = ax.get_xlim()
    y0, y1 = ax.get_ylim()
    bb = ax.get_window_extent()
    w_in, h_in = bb.width / fig.dpi, bb.height / fig.dpi
    px, py = (np.asarray(xs) - x0) / (x1 - x0), (np.asarray(ys) - y0) / (y1 - y0)
    lw = np.array([len(t) * fontsize * 0.62 / 72 / w_in for t in texts])   # label widths (axes units)
    lh = fontsize * 1.6 / 72 / h_in                                          # label height
    n = len(texts)
    lx = px + lw / 2 + 0.006 + rng.normal(0, 0.002, n)
    ly = py + rng.normal(0, 0.004, n)
    for it in range(iters):
        moved = 0.0
        for i in range(n):
            for j in range(i + 1, n):
                ox = (lw[i] + lw[j]) / 2 + 0.003 - abs(lx[i] - lx[j])
                oy = lh * 1.05 - abs(ly[i] - ly[j])
                if ox > 0 and oy > 0:
                    if oy <= ox * (w_in / h_in) * 0.15 or True:      # separate vertically (labels are wide)
                        d = np.sign(ly[i] - ly[j]) or rng.choice([-1, 1])
                        ly[i] += d * oy / 2
                        ly[j] -= d * oy / 2
                        moved += oy
        for i in range(n):                                            # keep labels off all points
            for k in range(n):
                if abs(px[k] - lx[i]) < lw[i] / 2 + 0.004 and abs(py[k] - ly[i]) < lh / 2 + 0.004:
                    d = np.sign(ly[i] - py[k]) or rng.choice([-1, 1])
                    ly[i] += d * lh * 0.5
                    moved += lh * 0.5
            # gentle pull back towards own point
            lx[i] += 0.05 * ((px[i] + lw[i] / 2 + 0.006) - lx[i])
            ly[i] += 0.03 * (py[i] - ly[i])
            lx[i] = min(max(lx[i], lw[i] / 2 + 0.002), 1 - lw[i] / 2 - 0.002)
            ly[i] = min(max(ly[i], lh / 2 + 0.002), 1 - lh / 2 - 0.002)
        if moved < 1e-4 and it > 20:
            break
    for i in range(n):
        tx, ty = x0 + lx[i] * (x1 - x0), y0 + ly[i] * (y1 - y0)
        left = tx - lw[i] / 2 * (x1 - x0)
        if np.hypot(lx[i] - lw[i] / 2 - px[i], ly[i] - py[i]) > 0.02:
            ax.plot([xs[i], left if abs(left - xs[i]) < abs(tx + lw[i] / 2 * (x1 - x0) - xs[i]) else
                     tx + lw[i] / 2 * (x1 - x0)], [ys[i], ty], color="grey", lw=0.5, zorder=1)
        ax.text(tx, ty, texts[i], ha="center", va="center", fontsize=fontsize, color=colors[i],
                zorder=3, bbox=dict(boxstyle="round,pad=0.12", fc="white", ec="none", alpha=0.75))


