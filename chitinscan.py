def mix64(x):
    with np.errstate(over="ignore"):
        x = (x ^ (x >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        x = (x ^ (x >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        return x ^ (x >> np.uint64(31))


def _keep(hashes, scale):
    thr = np.uint64((2 ** 64 - 1) // scale)
    return np.unique(hashes[hashes <= thr])


_DNA_LUT = np.full(256, 4, dtype=np.uint8)
for _i, _b in enumerate("ACGT"):
    _DNA_LUT[ord(_b)] = _i


def dna_sketch(contigs, k=DNA_K, scale=DNA_SCALE):
    """Canonical k-mer FracMinHash sketch of all sequences (sorted unique uint64 array)."""
    parts = []
    for seq in contigs.values():
        if len(seq) < k:
            continue
        codes = _DNA_LUT[np.frombuffer(seq.encode(), dtype=np.uint8)]
        n = len(codes) - k + 1
        bad = np.concatenate([[0], np.cumsum(codes > 3)])
        valid = (bad[k:k + n] - bad[:n]) == 0
        c = np.minimum(codes, 3).astype(np.uint64)
        fwd = np.zeros(n, dtype=np.uint64)
        rev = np.zeros(n, dtype=np.uint64)
        for i in range(k):
            fwd = (fwd << np.uint64(2)) | c[i:i + n]
            rev |= (np.uint64(3) - c[i:i + n]) << np.uint64(2 * i)
        canon = np.minimum(fwd, rev)[valid]
        parts.append(_keep(mix64(canon), scale))
    return np.unique(np.concatenate(parts)) if parts else np.array([], dtype=np.uint64)


_AA_LUT = np.full(256, 20, dtype=np.uint8)
for _i, _a in enumerate("ACDEFGHIKLMNPQRSTVWY"):
    _AA_LUT[ord(_a)] = _i


def protein_sketch(proteins, k=AA_K, scale=AA_SCALE):
    """FracMinHash sketch of amino-acid k-mers over a list of protein strings."""
    if not proteins:
        return np.array([], dtype=np.uint64)
    codes = _AA_LUT[np.frombuffer(("*".join(proteins)).encode(), dtype=np.uint8)]
    n = len(codes) - k + 1
    if n <= 0:
        return np.array([], dtype=np.uint64)
    bad = np.concatenate([[0], np.cumsum(codes > 19)])
    valid = (bad[k:k + n] - bad[:n]) == 0
    c = codes.astype(np.uint64)
    val = np.zeros(n, dtype=np.uint64)
    for i in range(k):
        val = val * np.uint64(20) + np.minimum(c[i:i + n], 19)
    return _keep(mix64(val[valid]), scale)


def pairwise_mash(sketches, k):
    """Return (distance matrix, Jaccard matrix). Distance = Mash distance (substitutions per site)."""
    n = len(sketches)
    J = np.eye(n)
    D = np.zeros((n, n))
    for a in range(n):
        for b in range(a + 1, n):
            inter = len(np.intersect1d(sketches[a], sketches[b], assume_unique=True))
            union = len(sketches[a]) + len(sketches[b]) - inter
            j = inter / union if union else 0.0
            J[a, b] = J[b, a] = j
            j_eff = j if inter > 0 else 0.5 / max(union, 1)      # avoid infinite distance
            d = -np.log(2 * j_eff / (1 + j_eff)) / k
            D[a, b] = D[b, a] = d
    return D, J


